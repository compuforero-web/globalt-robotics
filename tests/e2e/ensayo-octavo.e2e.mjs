// Prueba del montaje dedicado de la muestra con sus cuentas ficticias y su compilador.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
const { chromium } = createRequire(import.meta.url)('playwright');
const origen = 'http://127.0.0.1:18180';
const navegador = await chromium.launch();
try {
  const profesor = await navegador.newPage();
  await profesor.goto(origen + '/aula/');
  await profesor.click('#tab-entrar');
  await profesor.fill('#form-entrar [name=correo]', 'profesor.octavo@example.com');
  await profesor.fill('#form-entrar [name=clave]', readFileSync('.ensayo-octavo/profesor','utf8'));
  await profesor.click('#form-entrar button');
  await profesor.locator('#form-autorizacion:visible').waitFor();
  for (const casilla of await profesor.locator('#form-autorizacion input[type=checkbox]').all()) await casilla.check();
  await profesor.click('#form-autorizacion button');
  await profesor.locator('#vista-cursos:visible').waitFor();
  await profesor.goto(origen + '/programa/octavo.html');
  await profesor.getByRole('link', { name:/Abrir la primera fase/ }).click();
  await profesor.locator('.code-editor__input').fill(readFileSync('tests/fixtures/laboratorio/ultra-solucion.ino','utf8'));
  await profesor.click('#btn-check');
  await profesor.locator('#lesson-picker a[data-lesson="arduino-ultrasonico-alerta"]').waitFor({timeout:90000});
  await profesor.goto(origen + '/aula/familias.html');
  await profesor.locator('#alumno').selectOption({label:'Estudiante Sol · 8°'});
  await profesor.locator('[name=titulo]').fill('¿Cuándo debe frenar el robot?');
  await profesor.locator('[name=fecha]').fill('2026-11-30');
  await profesor.locator('[name=observacion]').fill('Explicó por qué se detiene a 20 cm.');
  await profesor.locator('#actividad button').click();
  await profesor.getByText('Actividad publicada.',{exact:true}).waitFor();
  const correo = 'ensayo.sol@example.com';
  await profesor.getByText('Invitar a un acudiente',{exact:true}).click();
  await profesor.locator('[name=correo]').fill(correo);
  await profesor.locator('#invitacion button').click();
  await profesor.locator('#generado:visible').waitFor();
  const codigo = await profesor.locator('#generado').inputValue();
  const familia = await navegador.newPage({viewport:{width:390,height:844}});
  await familia.goto(origen + '/aula/');
  await familia.click('#tab-registro');
  await familia.click('#btn-adulto');
  const form = familia.locator('#form-registro');
  await form.locator('[name=nombre]').fill('Familia Sol');
  await form.locator('[name=correo]').fill(correo);
  const clave = 'Solo-ensayo-octavo-2027';
  await form.locator('[name=clave]').fill(clave);
  await form.locator('[name=confirmacion]').fill(clave);
  await form.locator('[name=terminos]').check();
  await form.locator('[name=datos]').check();
  await form.locator('button[type=submit]').click();
  await familia.locator('#vista-correo:visible').waitFor();
  const enlace = execFileSync('bash',['deploy/ensayo-octavo/ensayo.sh','correo',correo],{encoding:'utf8'}).trim();
  await familia.goto(enlace);
  await familia.locator('#form-enlace [name=clave]').fill(clave);
  await familia.click('#btn-enlace');
  await familia.getByRole('link',{name:'Seguimiento familiar'}).click();
  await familia.locator('#vinculo [name=codigo]').fill(codigo);
  await familia.locator('#vinculo button').click();
  await familia.getByText('Explicó por qué se detiene a 20 cm.',{exact:true}).waitFor();
  assert.equal(await familia.locator('#historial article').count(),1);
  assert.doesNotMatch(await familia.locator('#historial').innerText(),/Viento/);
} finally {
  await navegador.close();
}
